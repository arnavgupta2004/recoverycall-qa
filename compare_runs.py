#!/usr/bin/env python3
"""Compare two archived STT runs (e.g. 28 s vs 12 s chunks) from their results.json files.

    python compare_runs.py outputs/runs/chunk28s outputs/runs/chunk12s -o outputs/runs/compare_28s_vs_12s.md

Both runs are re-scored with the current src/metrics.py and the current critical spans in
data/scripts.json, so a metric change applies to both sides equally. Transcripts are taken
from the archives as-is; no API calls are made. phone_ulaw_container is excluded from the
like-for-like tables because it covers only chunk 0, whose turns depend on the chunk length.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

from run_spike import load_scripts, score
from src.metrics import turn_missing

LIKE_FOR_LIKE = ["clean", "phone", "phone_noisy"]
DROPPED_BELOW, PARTIAL_BELOW = 0.5, 0.8


def load_run(run_dir: Path, scripts: dict) -> list[dict]:
    turns = {(s["id"], i): t for s in scripts["scenarios"] for i, t in enumerate(s["turns"])}
    records = json.loads((run_dir / "results.json").read_text(encoding="utf-8"))
    for rec in records:
        chunk_turns = [turns[(rec["scenario"], i)] for i in rec["turns"]]
        reference = " ".join(t["text"] for t in chunk_turns)
        if reference != rec["reference"]:
            raise SystemExit(f"{run_dir}: reference text for {rec['scenario']} turns {rec['turns']} differs from "
                             "data/scripts.json; the archive was made from a different script")
        rec["critical_spans"] = [dict(sp, turn=i) for i in rec["turns"] for sp in turns[(rec["scenario"], i)].get("critical_spans", [])]
        score(rec)
    return records


def usable(records: list[dict]) -> list[dict]:
    return [r for r in records if r["format"] == "verbatim" and r["transcript"] is not None
            and not r["script_mismatch"] and r["variant"] in LIKE_FOR_LIKE]


def turn_coverage(rec: dict, turn_text: dict) -> dict[int, str]:
    out = {}
    for t in rec["turns"]:
        missing, ratio = turn_missing(turn_text[(rec["scenario"], t)], rec["transcript"])
        out[t] = "dropped" if missing else ("partial" if ratio < PARTIAL_BELOW else "ok")
    return out


def span_label(s: dict) -> str:
    return s["status"] + (" NEG-LOST" if s.get("negation_missing") else "")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_a", type=Path)
    ap.add_argument("run_b", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    args = ap.parse_args()
    scripts = load_scripts()
    turn_text = {(s["id"], i): t["text"] for s in scripts["scenarios"] for i, t in enumerate(s["turns"])}
    name_a, name_b = args.run_a.name, args.run_b.name
    raw = {name_a: load_run(args.run_a, scripts), name_b: load_run(args.run_b, scripts)}
    runs = {k: usable(v) for k, v in raw.items()}

    L = [f"# STT run comparison: {name_a} vs {name_b}\n",
         f"Generated by `compare_runs.py` from `{args.run_a}/results.json` and `{args.run_b}/results.json`. "
         "Both runs are re-scored with the current `src/metrics.py` and the current critical spans in "
         "`data/scripts.json`; transcripts are the archived API outputs.\n",
         f"Included: `format=verbatim` runs on {', '.join(LIKE_FOR_LIKE)} that returned a transcript and passed the "
         "script check. Excluded: `phone_ulaw_container` (covers chunk 0 only, so its turns change with chunk "
         "length), ITN runs, and script mismatches (hi-IN on the Roman-script Hinglish call).\n",
         f"Turn coverage: each turn's reference text is fuzzy-matched against its chunk transcript with the same "
         f"word-window matcher as the spans. Ratio < {DROPPED_BELOW} = dropped (turns of 3 words or fewer: < 0.8), "
         f"< {PARTIAL_BELOW} = partial.\n"]

    L += ["## Span totals by variant\n",
          f"| variant | spans | {name_a} exact / near / garbled | {name_a} neg lost | "
          f"{name_b} exact / near / garbled | {name_b} neg lost |", "|---|---|---|---|---|---|"]
    for v in LIKE_FOR_LIKE:
        cells = []
        for k in (name_a, name_b):
            sp = [s for r in runs[k] if r["variant"] == v for s in r["spans"]]
            cells.append((len(sp), f"{sum(s['status'] == 'exact' for s in sp)} / {sum(s['status'] == 'near' for s in sp)} / "
                          f"{sum(s['status'] == 'garbled' for s in sp)}", sum(bool(s.get("negation_missing")) for s in sp)))
        L.append(f"| {v} | {cells[0][0]} vs {cells[1][0]} | {cells[0][1]} | {cells[0][2]} | {cells[1][1]} | {cells[1][2]} |")

    L += ["\n## WER and deletions by scenario, language and variant\n",
          f"| scenario | lang | variant | {name_a} WER | {name_b} WER | {name_a} del | {name_b} del |",
          "|---|---|---|---|---|---|---|"]
    agg = {}
    for k, recs in runs.items():
        g = defaultdict(lambda: [0, 0, 0])
        for r in recs:
            key = (r["scenario"], r["language_code"], r["variant"])
            g[key][0] += r["sub"] + r["del"] + r["ins"]
            g[key][1] += r["ref_words"]
            g[key][2] += r["del"]
        agg[k] = g
    for key in sorted(set(agg[name_a]) | set(agg[name_b])):
        a, b = agg[name_a].get(key), agg[name_b].get(key)
        wer = lambda x: f"{x[0] / x[1]:.3f}" if x and x[1] else "–"
        L.append(f"| {key[0]} | {key[1]} | {key[2]} | {wer(a)} | {wer(b)} | {a[2] if a else '–'} | {b[2] if b else '–'} |")

    L += ["\n## Turn coverage (dropped / partial turns)\n",
          f"| scenario | lang | variant | {name_a} | {name_b} |", "|---|---|---|---|---|"]
    cov = {}
    for k, recs in runs.items():
        c = defaultdict(dict)
        for r in recs:
            c[(r["scenario"], r["language_code"], r["variant"])].update(turn_coverage(r, turn_text))
        cov[k] = c
    fmt = lambda d: ", ".join(f"t{t} {s}" for t, s in sorted(d.items()) if s != "ok") or "all ok"
    for key in sorted(set(cov[name_a]) | set(cov[name_b])):
        L.append(f"| {key[0]} | {key[1]} | {key[2]} | {fmt(cov[name_a].get(key, {}))} | {fmt(cov[name_b].get(key, {}))} |")

    L += ["\n## Critical spans that are not exact in either run\n",
          f"| scenario | lang | variant | type | span | {name_a} | {name_b} | {name_b} best match |",
          "|---|---|---|---|---|---|---|---|"]
    spans = {}
    for k, recs in runs.items():
        spans[k] = {(r["scenario"], r["language_code"], r["variant"], s["type"], s["span"]): s
                    for r in recs for s in r["spans"]}
    for key in sorted(set(spans[name_a]) | set(spans[name_b])):
        a, b = spans[name_a].get(key), spans[name_b].get(key)
        if (a and a["status"] != "exact") or (b and b["status"] != "exact") or not (a and b):
            L.append(f"| {key[0]} | {key[1]} | {key[2]} | {key[3]} | {key[4]} | {span_label(a) if a else 'not run'} | "
                     f"{span_label(b) if b else 'not run'} | {(b['best_match'] if b else '') or '(nothing)'} |")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
